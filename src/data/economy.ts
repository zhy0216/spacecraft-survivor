export const DOCK_SHOP_REFRESH_PRICE = 10;

/**
 * —— 特价折扣(商店优化:每次上架选一件商品打折)——
 * 每次货架掷定(跨段那一帧 / 刷新武器货架)之后,在**还没售出的货架位**之间
 * 恰选一格打本折扣(World.rollShopDiscount,恒掷 1 次 rng —— 池空也掷,
 * 与两张货架同一条"消耗次数与池大小无关"的确定性口径)。半价档:
 * 武器 30 → 15(整数)、法令 25 → 13(round 取整,不许印 12.5)。
 * 只打"商品"(武器 / 法令):付费修复是服务不是商品,不参与折扣。
 */
export const SHOP_DISCOUNT_FRACTION = 0.5;

/**
 * 特价后的实际扣费 = round(base × SHOP_DISCOUNT_FRACTION),夹到 ≥ 1。
 * **World 扣费与 UI 印价共用这一份**(与 skipRefundFor 同一条"单一真相"纪律):
 * 两边分家的话,玩家看到的特价与到账的扣费就会各走各的。
 * 取整用 round 而不是 floor:与 upgradeCost 同一条口径(四舍五入贴住折扣曲线,
 * 累计不往下偏)。坏输入(NaN / 非正)一律夹回 1 —— 扣费绝不许扣出 0 或负数。
 */
export function shopDiscountPrice(base: number): number {
  // NaN / 非有限 / 非正一律夹回 1(注意 Math.max(1, NaN) 是 NaN,必须先挡):
  // 扣费绝不许扣出 0、负数或 NaN
  if (!Number.isFinite(base) || base <= 0) return 1;
  return Math.max(1, Math.round(base * SHOP_DISCOUNT_FRACTION));
}

